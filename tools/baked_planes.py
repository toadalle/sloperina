"""Export only authored AirWall faces as planar perimeters for the zone overlay."""
from collections import Counter, defaultdict
from pathlib import Path
import math

import phive

MAPS = {
    "KakarikoVillage": ("KakarikoVillage_Adult", "KakarikoVillage_Child"),
    "KokiriForest": ("KokiriForest_Adult", "KokiriForest_Child"),
    "DodongoCavern": ("DodongoCavern",),
    "ForestTemple": ("ForestTemple",),
    "InsideTheDekuTree": ("InsideTheDekuTree",),
}
SCALE = 16


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def cross(a, b):
    return (a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2], a[0]*b[1] - a[1]*b[0])


def perimeters(counts):
    links = defaultdict(set)
    for (a, b), n in counts.items():
        if n == 1:
            links[a].add(b)
            links[b].add(a)
    while links:
        start = min(links)
        todo, component = [start], set()
        while todo:
            p = todo.pop()
            if p not in component:
                component.add(p)
                todo.extend(links[p] - component)
        if all(len(links[p]) == 2 for p in component):
            loop = [start]
            nxt = min(links[start])
            while nxt != start:
                last = loop[-1]
                loop.append(nxt)
                nxt = next(p for p in links[nxt] if p != last)
            # Omit exactly collinear points without expanding the authored perimeter.
            loop = [p for i, p in enumerate(loop)
                    if any(cross(sub(p, loop[i-1]), sub(loop[(i+1) % len(loop)], p)))]
            if 3 <= len(loop) <= 16:
                yield loop
        for p in component:
            del links[p]


def read_map(area, name):
    planes = defaultdict(Counter)
    for path in phive.map_tiles(area, name):
        sc = phive.decode_bphsc(phive.load(path))
        triangles, _ = phive._tile_triangles(sc, False)
        for a, b, c, attrs in triangles:
            if not attrs["hitsPlayer"] or attrs["material"] != "AirWall":
                continue
            n = cross(sub(b, a), sub(c, a))
            length = math.sqrt(sum(v*v for v in n))
            if not length:
                continue
            flip = -1 if n[max(range(3), key=lambda i: abs(n[i]))] < 0 else 1
            n = tuple(flip * v / length for v in n)
            key = (*[round(v * 64) for v in n], round(sum(x*y for x, y in zip(n, a))*8))
            pts = [tuple(round(v*SCALE) for v in p) for p in (a, b, c)]
            if len(set(pts)) != 3 or any(not -32768 <= v <= 32767 for p in pts for v in p):
                continue
            planes[key].update(tuple(sorted((pts[i], pts[(i+1) % 3]))) for i in range(3))
    return [loop for group in planes.values() for loop in perimeters(group)]


def main():
    lines = ["/* Generated by tools/baked_planes.py. Coordinates are in 1/16 m. */",
             "static const baked_plane_t baked_planes[] = {"]
    index, start = [], 0
    for area, names in MAPS.items():
        for name in names:
            loops = read_map(area, name)
            print(name, len(loops), flush=True)
            if not loops:
                continue
            count = 0
            for loop in loops:
                centre = tuple(round(sum(p[i] for p in loop) / len(loop)) for i in range(3))
                radius = math.ceil(max(math.dist(centre, p) for p in loop))
                if radius < SCALE or radius > 65535:
                    continue
                points = ", ".join("{%d,%d,%d}" % p for p in loop)
                lines.append(f"  {{ {len(loop)}, {radius}, {{{centre[0]},{centre[1]},{centre[2]}}}, {{ {points} }} }},")
                count += 1
            if count:
                index.append(f'  {{ "{name}", {start}, {count} }},')
                start += count
    lines += ["};", "static const airmap_t baked_maps[] = {", *index, "};"]
    Path("src/ootgz/baked_planes.inc").write_text("\n".join(lines)+"\n", encoding="ascii")


if __name__ == "__main__":
    main()
